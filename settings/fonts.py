def installed_families():
    out = subprocess.run(["fc-list", ":", "family"], capture_output=True, text=True).stdout
    fams = set()
    for line in out.splitlines():
        for f in line.split(","):
            fams.add(f.strip())
    return fams


def available(options):
    """Only the fonts that are installed (the "Same as interface" entry always stays)."""
    fams = installed_families()
    return [(shown, fam) for shown, fam in options if not fam or fam in fams]


def gsettings_get(key):
    out = subprocess.run(["gsettings", "get", "org.gnome.desktop.interface", key],
                         capture_output=True, text=True).stdout.strip().strip("'")
    return re.sub(r"\s+\d+(\.\d+)?$", "", out)          # "Inter 11" -> "Inter"


def _xml(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def write_fontconfig(ui, mono, doc):
    """Preferred order for sans-serif / serif / monospace (Arch Wiki: "Fallback font order")."""
    def alias(generic, first):
        fams = [first] + {"sans-serif": ["Noto Sans"], "serif": ["Noto Serif"],
                          "monospace": ["Noto Sans Mono", "Symbols Nerd Font"]}[generic]
        fams += ["Noto Sans CJK SC", "Noto Color Emoji"]
        seen = []
        for f in fams:
            if f and f not in seen:
                seen.append(f)
        inner = "".join(f"<family>{_xml(f)}</family>" for f in seen)
        return f"  <alias>\n    <family>{generic}</family>\n    <prefer>{inner}</prefer>\n  </alias>\n"
    os.makedirs(os.path.dirname(FONTCONFIG), exist_ok=True)
    with open(FONTCONFIG, "w") as f:
        f.write('<?xml version="1.0"?>\n<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">\n'
                "<!-- Generated by Settings (Appearance -> Fonts). Preferred fonts for the generic families,\n"
                "     then Noto for wide Unicode coverage, Noto CJK and color emoji. -->\n<fontconfig>\n"
                + alias("sans-serif", ui) + alias("serif", doc or "Noto Serif") + alias("monospace", mono)
                + "</fontconfig>\n")


def apply_kitty(mono, size="11.5"):
    """kitty: change font_family and ask running kittys to reload their config (SIGUSR1)."""
    try:
        text = open(KITTY_CONF).read()
    except OSError:
        return
    line = f"font_family      {mono}"
    if re.search(r"^font_family\s.*$", text, re.M):
        text = re.sub(r"^font_family\s.*$", line, text, flags=re.M)
    else:
        text = line + "\n" + text
    with open(KITTY_CONF, "w") as f:
        f.write(text)
    out = subprocess.run(["pgrep", "-x", "kitty"], capture_output=True, text=True).stdout.split()
    for pid in out:
        try:
            os.kill(int(pid), signal.SIGUSR1)
        except (OSError, ValueError):
            pass


def apply(ui, mono, doc, size="11"):
    """Apply all three: GNOME settings (GTK apps), fontconfig (everything else) and kitty."""
    run = lambda k, v: subprocess.run(["gsettings", "set", "org.gnome.desktop.interface", k, v])  # noqa: E731
    run("font-name", f"{ui} {size}")
    run("monospace-font-name", f"{mono} {size}")
    run("document-font-name", f"{doc or ui} {size}")
    write_fontconfig(ui, mono, doc)
    subprocess.run(["fc-cache", "-f"], capture_output=True)
    apply_kitty(mono)
